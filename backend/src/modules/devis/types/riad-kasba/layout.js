function expandItem(row) {
  const [kind, ...args] = row;
  if (kind === 't') {
    const [style, x, y, w, s, opts = {}] = args;
    const [font, size, color] = STYLES[style];
    const { runs, ...rest } = opts;
    return { t: 'txt', x, y, w, font, size, color, ...(runs ? { runs } : { s }), fit: 'exact', ...rest };
  }
  if (kind === 'i') {
    const [f, x, y, w, h] = args;
    return { t: 'img', f, x, y, w, h };
  }
  if (kind === 'r') {
    const [x, y, w, h, fill, op] = args;
    return { t: 'rect', x, y, w, h, fill, ...(op !== undefined ? { op } : {}) };
  }
  if (kind === 's') {
    const [x, y, w, h, stroke, sw] = args;
    return { t: 'srect', x, y, w, h, stroke, sw };
  }
  throw new Error(`Élément de layout inconnu : ${kind}`);
}

